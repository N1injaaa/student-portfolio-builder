-- Миграция: добавляет платный статус (is_pro) в уже существующую базу.
-- Выполнить один раз в Supabase → SQL Editor → New query → Run.
-- (schema.sql уже обновлён этим же изменением — этот файл только для того,
-- чтобы применить его к базе, которая была создана ДО этого изменения.)
-- ============================================================================

alter table public.profiles
  add column if not exists is_pro boolean not null default false;

-- Важно: RLS-политика "profiles_update_own" разрешает пользователю обновлять
-- СВОЮ строку целиком — включая любую колонку, если её явно не запретить.
-- Без строки ниже пользователь мог бы через консоль браузера выполнить
--   supabase.from("profiles").update({ is_pro: true }).eq("user_id", ...)
-- и получить Pro бесплатно. Эта команда запрещает именно колонку is_pro
-- для обычных пользователей — остальные поля (data, username и т.д.)
-- продолжают обновляться как раньше. Менять is_pro сможет только
-- Table Editor / SQL Editor в самой Supabase (то есть ты вручную).
revoke update (is_pro) on public.profiles from authenticated;
